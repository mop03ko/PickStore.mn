import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const js=fs.readFileSync('app.js','utf8');
const html=fs.readFileSync('index.html','utf8');
const css=fs.readFileSync('styles.css','utf8');
const logo=fs.readFileSync('assets/pick-store.svg','utf8');
new vm.Script(js);
assert.match(html,/<html lang="mn">/);
assert.match(logo,/#ec1f2f/);
assert.match(css,/@media\(max-width:540px\)/);
const required=['search-form','search','sort','product-grid','cart-content','cart-dialog','product-dialog','info-dialog','mega-menu','empty-state','toast'];
for (const id of required) assert(html.includes('id="'+id+'"'), 'Missing element '+id);
const stub={textContent:'',hidden:false,value:'',innerHTML:'',setAttribute(){},classList:{toggle(){},add(){},remove(){}},addEventListener(){}};
const context=vm.createContext({Intl,Set,JSON,Number,Array,Object,String,console,setTimeout,clearTimeout,localStorage:{getItem(){return null},setItem(){}},document:{querySelector(){return {...stub,classList:stub.classList}},querySelectorAll(){return []},addEventListener(){}}});
vm.runInContext(js,context);
const run=code=>vm.runInContext(code,context);
assert.equal(run('products.length'),12);
assert.equal(run('filteredProducts().length'),12);
run("state.category='Gaming'");
assert.equal(run('filteredProducts().length'),3);
run("state.category='all';state.query='macbook'");
assert.equal(run('filteredProducts()[0].brand'),'Apple');
run("state.query='';state.mode='saved'");
assert.equal(run('filteredProducts().length'),0);
run("saved.add(1)");
assert.equal(run('filteredProducts().length'),1);
run("state.mode='all';state.brand='DJI'");
assert.equal(run('filteredProducts().length'),2);
run("state.brand='';state.mode='deals'");
assert.equal(run('filteredProducts().every(p=>p.old>p.price)'),true);
run("state.mode='all';state.sort='price-asc'");
assert.equal(run('filteredProducts()[0].price'),159000);
run("cart=[{id:1,qty:2},{id:4,qty:1}]");
assert.equal(run('cart.reduce((n,x)=>n+products.find(p=>p.id===x.id).price*x.qty,0)'),7969000);
run("state.query='<script>alert(1)</script>'");
assert.equal(run('filteredProducts().length'),0);
console.log('PASS: syntax, page hooks, 4 categories, search, saved products, brand filter, deals, sorting and cart arithmetic.');
